#!/usr/bin/env python3
# Writes lib/cw-commons/TzDb.h: timezone names (as the settings page offers them) and their POSIX rules.
# Source: https://github.com/nayarsystems/posix_tz_db (zones.csv). Run it again to update the table:
#   python3 tools/gen_tzdb.py [zones.csv]
import csv, io, os, sys, urllib.request

URL = "https://raw.githubusercontent.com/nayarsystems/posix_tz_db/master/zones.csv"
# Names the browser may list that the source does not have (renamed zones): alias -> name in the source
ALIASES = {
    "UTC": "Etc/UTC", "GMT": "Etc/GMT", "Europe/Kyiv": "Europe/Kiev", "Asia/Calcutta": "Asia/Kolkata",
    "Asia/Rangoon": "Asia/Yangon", "Atlantic/Faeroe": "Atlantic/Faroe", "Pacific/Kanton": "Pacific/Enderbury",
    "America/Ciudad_Juarez": "America/Ojinaga",
}

here = os.path.dirname(os.path.abspath(__file__))
out = os.path.join(here, "..", "lib", "cw-commons", "TzDb.h")
raw = open(sys.argv[1], encoding="utf-8").read() if len(sys.argv) > 1 else urllib.request.urlopen(URL).read().decode("utf-8")
zones = {name: rule for name, rule in csv.reader(io.StringIO(raw))}
for alias, name in ALIASES.items():
    if alias not in zones and name in zones:
        zones[alias] = zones[name]

lines = [
    "// Generated by tools/gen_tzdb.py from github.com/nayarsystems/posix_tz_db: do not edit.",
    "// Timezone name -> POSIX rule, sorted by name (byte order) for the binary search in CWTime.cpp.",
    "#pragma once",
    "",
    "struct CWTzEntry { const char *name; const char *posix; };",
    "",
    "static const CWTzEntry CW_TZ_DB[] = {",
]
for name in sorted(zones):
    lines.append('  {"%s", "%s"},' % (name, zones[name].replace("\\", "\\\\").replace('"', '\\"')))
lines += ["};", "", "static const unsigned CW_TZ_DB_SIZE = sizeof(CW_TZ_DB) / sizeof(CW_TZ_DB[0]);", ""]
open(out, "w", encoding="utf-8").write("\n".join(lines))
print("%d zones -> %s" % (len(zones), os.path.normpath(out)))
